// The test network every derivation test runs against.
//
// IT TAKES ITS COUNTS AS PARAMETERS AND CARRIES BOTH ADDRESS FAMILIES, as the spec asks of
// every fixture: nothing in the code under test may presuppose how many interfaces or
// clients exist or which family an address is. The addresses below are example values a
// test is allowed to hold; the code under test reads them back out of the rows and never
// names one.
//
// Its shape: interfaceCount inside interfaces, each holding one IPv4 and one IPv6 prefix,
// plus one upstream interface with a gateway behind it; clientCount clients spread over the
// inside interfaces, alternating families, every third one leased and the rest seen only in
// flows. Flows of every direction are generated by flowsFor.

// testNetwork is a database with a network in it.
type Network struct {
	DB         *store.Store
	Now        int64
	Inside     []Interface
	Upstream   Interface
	Clients    []Client
	RuleID     int64
	DigestSeed int
}

type Interface struct {
	ID      int64
	Device  string
	Address string
	Prefix  int64
	Family  int64
	V6      string
}

type Client struct {
	Address     string
	InterfaceID int64
	Device      string
	Leased      bool
	V6          bool
}

// ReferenceNow is a fixed instant in the middle of a UTC hour, so a test can place flows on
// either side of hour, day, week and month boundaries by arithmetic.
const ReferenceNow int64 = 1790000000

// newTestNetwork builds the network and returns it.
func NewNetwork(t *testing.T, interfaceCount, clientCount int) *Network {
	t.Helper()
	database := Open(t)
	ctx := context.Background()
	network := &Network{DB: database, Now: ReferenceNow}

	for index := 0; index < interfaceCount; index++ {
		identifier := fmt.Sprintf("example_if_%d", index)
		device := fmt.Sprintf("exdev%d", index)
		id, err := database.UpsertInterface(ctx, vocab.Interface{
			Identifier: identifier, Device: device,
			Description: fmt.Sprintf("example description %d", index),
			LinkType:    "example-link", LinkKind: "other",
		}, network.Now-86400)
		if err != nil {
			t.Fatalf("writing an interface: %v", err)
		}
		iface := Interface{
			ID: id, Device: device, Family: 4,
			Address: fmt.Sprintf("10.%d.0.1", index+1), Prefix: 24,
			V6: fmt.Sprintf("fd00:%x::1", index+1),
		}
		network.Inside = append(network.Inside, iface)
		bits4, bits6 := int64(24), int64(64)
		for _, address := range []vocab.InterfaceAddress{
			{InterfaceID: id, SourceField: vocab.SourceFieldAddr4, Address: iface.Address, PrefixLength: &bits4, AddressFamily: 4},
			{InterfaceID: id, SourceField: vocab.SourceFieldAddr6, Address: iface.V6, PrefixLength: &bits6, AddressFamily: 6},
		} {
			if err := database.UpsertInterfaceAddress(ctx, address, nil, network.Now-86400); err != nil {
				t.Fatalf("writing an interface address: %v", err)
			}
		}
		// What discovery proposes from the same two addresses: their networks.
		if err := database.DetectNetworks(ctx, id, []netip.Prefix{
			netip.PrefixFrom(netip.MustParseAddr(iface.Address), int(bits4)).Masked(),
			netip.PrefixFrom(netip.MustParseAddr(iface.V6), int(bits6)).Masked(),
		}, network.Now-86400); err != nil {
			t.Fatalf("detecting the networks: %v", err)
		}
	}

	upstreamID, err := database.UpsertInterface(ctx, vocab.Interface{
		Identifier: "example_if_upstream", Device: "exdevup",
		Description: "example description upstream",
		LinkType:    "example-link", LinkKind: "other", IsUpstream: true,
	}, network.Now-86400)
	if err != nil {
		t.Fatalf("writing the upstream interface: %v", err)
	}
	network.Upstream = Interface{ID: upstreamID, Device: "exdevup", Address: "203.0.113.2", Prefix: 24, Family: 4}
	bits := int64(24)
	for _, address := range []vocab.InterfaceAddress{
		{InterfaceID: upstreamID, SourceField: vocab.SourceFieldAddr4, Address: "203.0.113.2", PrefixLength: &bits, AddressFamily: 4},
		{InterfaceID: upstreamID, SourceField: vocab.SourceFieldGateways, Address: "203.0.113.1", AddressFamily: 4},
	} {
		if err := database.UpsertInterfaceAddress(ctx, address, nil, network.Now-86400); err != nil {
			t.Fatalf("writing an upstream address: %v", err)
		}
	}
	if err := database.DetectNetworks(ctx, upstreamID, []netip.Prefix{
		netip.PrefixFrom(netip.MustParseAddr("203.0.113.2"), 24).Masked(),
	}, network.Now-86400); err != nil {
		t.Fatalf("detecting the upstream network: %v", err)
	}

	network.RuleID, err = database.UpsertRule(ctx, vocab.Rule{
		PfLabel: "example-rule-label", Description: "example rule", Action: "pass",
	}, network.Now-86400)
	if err != nil {
		t.Fatalf("writing a rule: %v", err)
	}

	// Any registered lease provider: the leases are the network's, and which built-in server issued
	// them is no fact this network presupposes.
	var leaseBackend string
	if err := database.DB().QueryRowContext(ctx, "SELECT provider_key FROM provider WHERE kind = 'dhcp_lease' "+
		"ORDER BY provider_key LIMIT 1").Scan(&leaseBackend); err != nil {
		t.Fatalf("looking up a lease provider: %v", err)
	}
	leaseProvider, err := database.ProviderID(ctx, "dhcp_lease", leaseBackend)
	if err != nil {
		t.Fatalf("looking up a lease provider: %v", err)
	}
	for index := 0; index < clientCount; index++ {
		iface := network.Inside[index%len(network.Inside)]
		host := 10 + index/len(network.Inside)
		client := Client{InterfaceID: iface.ID, Device: iface.Device, Leased: index%3 == 0,
			V6: index%2 == 1}
		if client.V6 {
			client.Address = fmt.Sprintf("fd00:%x::%x", (index%len(network.Inside))+1, host)
		} else {
			client.Address = fmt.Sprintf("10.%d.0.%d", (index%len(network.Inside))+1, host)
		}
		if client.Leased {
			mac := fmt.Sprintf("00:00:00:00:%02x:%02x", index/256, index%256)
			clientID, err := database.UpsertClient(ctx, vocab.Client{
				Identity:    vocab.ClientIdentity{Kind: vocab.IdentityMAC, Key: mac},
				InterfaceID: &iface.ID, MAC: &mac, LastAddress: &client.Address,
			}, network.Now-3600)
			if err != nil {
				t.Fatalf("writing a leased client: %v", err)
			}
			expiry := network.Now + 3600
			if err := database.InsertDHCPLease(ctx, leaseProvider, vocab.DHCPLease{
				ClientID: &clientID, Backend: leaseBackend, Address: client.Address, MAC: &mac,
				LeaseState: "active", InterfaceID: &iface.ID,
				GenerationKey: vocab.GenerationKeyOf(nil, &expiry, 0), ExpiresAt: &expiry,
				ObservedAt: network.Now - 3600,
			}); err != nil {
				t.Fatalf("writing a lease: %v", err)
			}
		}
		network.Clients = append(network.Clients, client)
	}
	return network
}

// Outside returns the k-th outside address of a family.
func Outside(k int, v6 bool) string {
	if v6 {
		return fmt.Sprintf("2001:db8::%x", k+1)
	}
	return fmt.Sprintf("198.51.100.%d", (k%250)+1)
}

// networkFlow is one generated record.
type Flow struct {
	ObservedAt int64
	Device     string
	Direction  string
	Src, Dst   string
	DstPort    *int64
	SrcPort    *int64
	IPID       *int64
	TCPSeq     *int64
	Protocol   string
	Action     string
	Reason     *string
	Bytes      int64
	RuleID     *int64
	IngestedAt int64
}

// Insert stores the records unplaced, as the collector does.
func (n *Network) Insert(t *testing.T, specs []Flow) []string {
	t.Helper()
	ctx := context.Background()
	var addresses []string
	for _, spec := range specs {
		n.DigestSeed++
		version := int64(4)
		if ContainsColon(spec.Src) {
			version = 6
		}
		rid := "example-rule-label"
		state := vocab.LookupNotFound
		if spec.RuleID != nil {
			state = vocab.LookupResolved
		}
		ingested := spec.IngestedAt
		if ingested == 0 {
			// Written a second before the refresh that follows, as a pass's rows are: a row
			// stamped in the same second as a refresh is stale to it by rule 3.
			ingested = n.Now - 1
		}
		if err := n.DB.InsertFlow(ctx, vocab.Flow{
			LogDigest: fmt.Sprintf("example-digest-%d", n.DigestSeed), ObservedAt: spec.ObservedAt,
			IngestedAt: ingested, InterfaceDevice: spec.Device, InterfaceLookupState: vocab.LookupResolved,
			SrcAddress: spec.Src, DstAddress: spec.Dst, DstPort: spec.DstPort, Protocol: spec.Protocol,
			IPVersion: version, Action: spec.Action, Direction: spec.Direction, LogReason: spec.Reason,
			PacketBytes: spec.Bytes, Rid: &rid, RuleID: spec.RuleID, RuleLookupState: state,
			SrcPort: spec.SrcPort, IPID: spec.IPID, TCPSeq: spec.TCPSeq,
		}); err != nil {
			t.Fatalf("writing a flow: %v", err)
		}
		addresses = append(addresses, spec.Src, spec.Dst)
	}
	return addresses
}

func ContainsColon(text string) bool {
	for index := 0; index < len(text); index++ {
		if text[index] == ':' {
			return true
		}
	}
	return false
}

// FlowsFor generates count records ending at the network's now, spread back over span
// seconds, of every direction: a client to the outside logged inbound on its own interface,
// the outside to a client logged on the upstream interface, a client to a client of another
// interface, and an unsolicited packet to the firewall's own upstream address. Blocked
// records carry each kind of reason.
func (n *Network) FlowsFor(count int, span int64) []Flow {
	reasons := []*string{Ptr(vocab.LogReasonMatch), Ptr("state-mismatch"), nil, Ptr("unknown(16)")}
	var specs []Flow
	for index := 0; index < count; index++ {
		client := n.Clients[index%len(n.Clients)]
		other := n.Clients[(index*7+3)%len(n.Clients)]
		observed := n.Now - (int64(index) * span / int64(count+1)) - 1
		port := int64(443 + index%3)
		spec := Flow{ObservedAt: observed, Protocol: "tcp", Action: "pass",
			Bytes: int64(60 + (index*37)%1400), DstPort: &port}
		if index%5 == 0 {
			spec.Action = "block"
			spec.Reason = reasons[(index/5)%len(reasons)]
		}
		// A reject is a refusal too, and a record whose action could not be named is neither
		// allowed nor blocked.
		if index%13 == 0 {
			spec.Action = "reject"
		}
		if index%17 == 0 {
			spec.Action = "unknown"
		}
		if index%4 == 0 {
			spec.RuleID = &n.RuleID
		}
		if index%9 == 0 {
			spec.Protocol, spec.DstPort = "icmp", nil
		}
		switch index % 4 {
		case 0, 1:
			spec.Device, spec.Direction = client.Device, "in"
			spec.Src, spec.Dst = client.Address, Outside(index, client.V6)
		case 2:
			spec.Device, spec.Direction = n.Upstream.Device, "in"
			spec.Src, spec.Dst = Outside(index, client.V6), client.Address
		default:
			if other.V6 == client.V6 && other.Address != client.Address {
				spec.Device, spec.Direction = client.Device, "in"
				spec.Src, spec.Dst = client.Address, other.Address
			} else {
				spec.Device, spec.Direction = n.Upstream.Device, "in"
				spec.Src, spec.Dst = Outside(index, false), n.Upstream.Address
			}
		}
		specs = append(specs, spec)
	}
	return specs
}

func Ptr[T any](value T) *T { return &value }

// ClassifyAndRefresh runs what the collector runs after a pass.
func (n *Network) ClassifyAndRefresh(t *testing.T, addresses []string) aggregates.Refresh {
	t.Helper()
	ctx := context.Background()
	if _, err := n.DB.Reclassify(ctx, addresses, n.Now); err != nil {
		t.Fatalf("classifying: %v", err)
	}
	refresh, err := RefreshAggregates(ctx, n.DB, 0, n.Now, nil)
	if err != nil {
		t.Fatalf("refreshing: %v", err)
	}
	return refresh
}

// Populated returns a network with flows over the last span seconds, classified and
// refreshed.
func Populated(t *testing.T, interfaceCount, clientCount, flowCount int, span int64) *Network {
	t.Helper()
	network := NewNetwork(t, interfaceCount, clientCount)
	addresses := network.Insert(t, network.FlowsFor(flowCount, span))
	network.ClassifyAndRefresh(t, addresses)
	return network
}

// QueryInt reads one integer.
func QueryInt(t *testing.T, database *store.Store, query string, arguments ...any) int64 {
	t.Helper()
	var value int64
	if err := database.DB().QueryRowContext(context.Background(), query, arguments...).Scan(&value); err != nil {
		t.Fatalf("%s: %v", query, err)
	}
	return value
}

// ForeignKeyViolations counts the rows of the core tables whose foreign key names a row that does
// not exist. PostgreSQL enforces every foreign key on every statement, so this is zero unless a
// constraint is missing or was dropped; the check is kept to assert that it is not. Every foreign
// key of the core schema is read from the catalogue and checked by its own columns.
func ForeignKeyViolations(t *testing.T, database *store.Store) int {
	t.Helper()
	ctx := context.Background()
	rows, err := database.DB().QueryContext(ctx, `
		SELECT c.conrelid::regclass::text, c.confrelid::regclass::text,
		       (SELECT string_agg(quote_ident(a.attname), ',' ORDER BY k.ordinality)
		        FROM unnest(c.conkey) WITH ORDINALITY AS k(attnum, ordinality)
		        JOIN pg_attribute AS a ON a.attrelid = c.conrelid AND a.attnum = k.attnum),
		       (SELECT string_agg(quote_ident(a.attname), ',' ORDER BY k.ordinality)
		        FROM unnest(c.confkey) WITH ORDINALITY AS k(attnum, ordinality)
		        JOIN pg_attribute AS a ON a.attrelid = c.confrelid AND a.attnum = k.attnum)
		FROM pg_constraint AS c
		JOIN pg_namespace AS n ON n.oid = c.connamespace
		WHERE c.contype = 'f' AND n.nspname = $1`, sqldb.CoreSchema)
	if err != nil {
		t.Fatalf("listing the foreign keys: %v", err)
	}
	type key struct{ child, parent, childColumns, parentColumns string }
	var keys []key
	for rows.Next() {
		var k key
		if err := rows.Scan(&k.child, &k.parent, &k.childColumns, &k.parentColumns); err != nil {
			t.Fatal(err)
		}
		keys = append(keys, k)
	}
	_ = rows.Close()
	violations := 0
	for _, k := range keys {
		var count int
		query := "SELECT count(*) FROM " + k.child + " AS child WHERE (" + k.childColumns +
			") IS NOT NULL AND NOT EXISTS (SELECT 1 FROM " + k.parent + " AS parent WHERE (" +
			PrefixColumns("parent", k.parentColumns) + ") = (" + PrefixColumns("child", k.childColumns) + "))"
		if err := database.DB().QueryRowContext(ctx, query).Scan(&count); err != nil {
			t.Fatalf("checking %s -> %s: %v", k.child, k.parent, err)
		}
		violations += count
	}
	return violations
}

// PrefixColumns qualifies a comma-separated column list with an alias.
func PrefixColumns(alias, columns string) string {
	parts := strings.Split(columns, ",")
	for index, column := range parts {
		parts[index] = alias + "." + column
	}
	return strings.Join(parts, ", ")
}

// Connection describes one client connection to an outside address.
type Connection struct {
	Client Client
	Peer   string
	At     int64
	IPID   int64
	Seq    int64
	// Lag is how long after the first leg the second was logged.
	Lag int64
}

// Legs returns the client's `in` record and the `out` record on the upstream interface:
// over IPv4 the second leg's source is the firewall's upstream address and its port
// another, as outbound NAT writes it; over IPv6 it is the client's, untranslated.
func (n *Network) Legs(c Connection, upstream6 string) (Flow, Flow) {
	port := int64(443)
	clientPort := int64(41000 + c.IPID%1000)
	natPort := int64(52000 + c.IPID%1000)
	seq := c.Seq
	first := Flow{ObservedAt: c.At, Device: c.Client.Device, Direction: "in", Src: c.Client.Address,
		Dst: c.Peer, DstPort: &port, SrcPort: &clientPort, TCPSeq: &seq, Protocol: "tcp", Action: "pass",
		Bytes: 60}
	second := first
	second.Device, second.Direction, second.ObservedAt = n.Upstream.Device, "out", c.At+c.Lag
	if c.Client.V6 {
		_ = upstream6
		return first, second
	}
	id := c.IPID
	first.IPID, second.IPID = &id, &id
	second.Src, second.SrcPort = n.Upstream.Address, &natPort
	return first, second
}

// DerivePairs classifies what was stored and pairs and refreshes the window, as a
// derivation does.
func (n *Network) DerivePairs(t *testing.T, addresses []string, from, to int64) flows.Pairing {
	t.Helper()
	ctx := context.Background()
	if _, err := n.DB.Reclassify(ctx, addresses, n.Now); err != nil {
		t.Fatalf("classifying: %v", err)
	}
	paired, err := n.DB.Pair(ctx, from, to, flows.DefaultPairingWindowSeconds)
	if err != nil {
		t.Fatalf("pairing: %v", err)
	}
	if _, err := RefreshAggregates(ctx, n.DB, 0, n.Now, paired.FlowInstants); err != nil {
		t.Fatalf("refreshing: %v", err)
	}
	return paired
}

// PairState renders every record's outcome and partner by what the record is -- its
// interface, its ends and its instant -- so two databases can be compared whatever ids
// and digests they gave the rows.
func PairState(t *testing.T, database *store.Store) string {
	t.Helper()
	rows, err := database.DB().Query(`SELECT f.interface_device || ' ' || f.src_address || ' ' || f.dst_address || ' ' || f.observed_at,
		coalesce(f.pair_outcome, '-'),
		coalesce(p.interface_device || ' ' || p.src_address || ' ' || p.dst_address || ' ' || p.observed_at, '-')
		FROM flow AS f LEFT JOIN flow AS p ON p.id = f.paired_flow_id`)
	if err != nil {
		t.Fatalf("reading the pairs: %v", err)
	}
	defer func() { _ = rows.Close() }()
	var lines []string
	for rows.Next() {
		var digest, outcome, partner string
		if err := rows.Scan(&digest, &outcome, &partner); err != nil {
			t.Fatalf("reading the pairs: %v", err)
		}
		lines = append(lines, digest+" "+outcome+" "+partner)
	}
	sort.Strings(lines)
	return strings.Join(lines, "\n")
}

// OutcomeOf reads one record's outcome and its partner's address pair.
func OutcomeOf(t *testing.T, database *store.Store, device, src, dst string) (string, string) {
	t.Helper()
	var outcome, partner string
	if err := database.DB().QueryRow(`SELECT coalesce(f.pair_outcome, '-'),
		coalesce(p.interface_device || ' ' || p.src_address || ' ' || p.dst_address, '-')
		FROM flow AS f LEFT JOIN flow AS p ON p.id = f.paired_flow_id
		WHERE f.interface_device = $1 AND f.src_address = $2 AND f.dst_address = $3`, device, src, dst).
		Scan(&outcome, &partner); err != nil {
		t.Fatalf("reading the record %s %s -> %s: %v", device, src, dst, err)
	}
	return outcome, partner
}

func ClientsOfFamily(network *Network, v6 bool) []Client {
	var clients []Client
	for _, client := range network.Clients {
		if client.V6 == v6 {
			clients = append(clients, client)
		}
	}
	return clients
}

// PlanNode is one node of a statement's plan: its type, the relation it reads and the index it
// reads it through.
type PlanNode struct {
	Type, Relation, Alias, Index string
}

// PlanOf plans a statement with sequential scans disabled and returns its nodes. With them
// disabled, PostgreSQL still chooses a sequential scan only where no index can serve the
// statement at all, so a test asserting that an index serves a statement and no growing table is
// scanned asserts what the plan checks of sql/schema-checks.sh assert at scale, on any table
// size.
func PlanOf(t testing.TB, s *store.Store, text string, arguments ...any) []PlanNode {
	t.Helper()
	text, arguments = Bound(t, text, arguments...)
	ctx := context.Background()
	tx, err := s.SQL.BeginTx(ctx, &sql.TxOptions{ReadOnly: true})
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = tx.Rollback() }()
	if _, err := tx.ExecContext(ctx, "SET LOCAL enable_seqscan = off"); err != nil {
		t.Fatal(err)
	}
	var plan string
	if err := tx.QueryRowContext(ctx, "EXPLAIN (FORMAT JSON) "+text, arguments...).Scan(&plan); err != nil {
		t.Fatalf("planning: %v", err)
	}
	var decoded any
	if err := json.Unmarshal([]byte(plan), &decoded); err != nil {
		t.Fatal(err)
	}
	var nodes []PlanNode
	var walk func(node any)
	walk = func(node any) {
		switch typed := node.(type) {
		case map[string]any:
			if kind, ok := typed["Node Type"].(string); ok {
				relation, _ := typed["Relation Name"].(string)
				alias, _ := typed["Alias"].(string)
				index, _ := typed["Index Name"].(string)
				nodes = append(nodes, PlanNode{Type: kind, Relation: relation, Alias: alias, Index: index})
			}
			for _, value := range typed {
				walk(value)
			}
		case []any:
			for _, element := range typed {
				walk(element)
			}
		}
	}
	walk(decoded)
	return nodes
}

// Scans reports the sequential scans of a table in a plan.
func Scans(nodes []PlanNode, table string) bool {
	for _, node := range nodes {
		if node.Type == "Seq Scan" && node.Relation == table {
			return true
		}
	}
	return false
}

// UsesIndex reports whether a plan reads an index, through any alias or through the one named.
func UsesIndex(nodes []PlanNode, index, alias string) bool {
	for _, node := range nodes {
		if node.Index == index && (alias == "" || node.Alias == alias) {
			return true
		}
	}
	return false
}

// prefixesOf parses ranges a test writes.
func Prefixes(t *testing.T, texts ...string) []netip.Prefix {
	t.Helper()
	var prefixes []netip.Prefix
	for _, text := range texts {
		prefix, err := netip.ParsePrefix(text)
		if err != nil {
			t.Fatalf("parsing %s: %v", text, err)
		}
		prefixes = append(prefixes, prefix)
	}
	return prefixes
}

// Bound turns a :name statement and its database/sql named arguments into the statement PostgreSQL
// runs and its arguments in order (internal/store/sqldb, translate.go). A text with no named
// argument is returned as it is.
func Bound(t testing.TB, text string, arguments ...any) (string, []any) {
	t.Helper()
	parameters := map[string]any{}
	named := false
	for _, argument := range arguments {
		if one, isNamed := argument.(sql.NamedArg); isNamed {
			parameters[one.Name] = one.Value
			named = true
		}
	}
	if !named {
		return text, arguments
	}
	translation, err := sqldb.Translate(text)
	if err != nil {
		t.Fatal(err)
	}
	ordered, err := translation.Arguments(parameters)
	if err != nil {
		t.Fatal(err)
	}
	return translation.Text, ordered
}
